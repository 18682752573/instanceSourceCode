package com.snailws.taskscompleted.activity;

/**
 * 找规律：3423523564576547457，后面的数字应该是什么？
 *
 * 规律分析：
 * 将数列分成每组3个元素的分组：
 *   第1组: (3, 4, 2)
 *   第2组: (3, 5, 2)
 *   第3组: (3, 5, 6)
 *   第4组: (4, 5, 7)
 *   第5组: (6, 5, 4)
 *   第6组: (7, 4, 5)
 *   第7组: (7, ?, ?)  ← 第19位已知为7
 *
 * 将相邻元素之差，再按每3个差值为一块分组，各块之和为：
 *   [0, 0, 1, 2, 1, 0]  —— 这是以帕斯卡三角第2行 (1,2,1) 为核心的对称序列
 *
 * 第1组和第4组的差值块均为 [+1, -2, +1]（绝对值 1,2,1 相同）。
 * 按照"3块为一周期"的规律，第7组差值块同样为 [+1, -2, +1]，因此：
 *   第20位 = 7 + 1 = 8
 *   第21位 = 8 - 2 = 6
 *   第22位 = 6 + 1 = 7
 *
 * 答：后面的数字是 8。
 */
public class SequencePatternUtil {

    // 原始数列：3423523564576547457（第1位至第19位）
    private static final int[] SEQUENCE_3423523564576547457 =
            {3, 4, 2, 3, 5, 2, 3, 5, 6, 4, 5, 7, 6, 5, 4, 7, 4, 5, 7};

    /**
     * 返回数列 3423523564576547457 的第20位数字。
     *
     * <p>规律：第7组差值块与第1组、第4组相同，均为 [+1, -2, +1]。
     * 第19位为 7，所以第20位 = 7 + 1 = 8。</p>
     *
     * @return 8
     */
    public static int getNextNumberInSequence3423523564576547457() {
        int[] seq = SEQUENCE_3423523564576547457;
        // 第7组差值块的第一个差为 +1（与第1组和第4组相同）
        return seq[seq.length - 1] + 1;
    }
}
